/**
 * Regenerates src/ui/usPaths.ts from the us-atlas Albers state shapes
 * (public domain, U.S. Census cartographic boundaries). Run with:
 *   node scripts/build-us-map.mjs
 * The output is committed, so the app and CI never need these packages at runtime.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { feature } from 'topojson-client';
import { presimplify, simplify, quantile } from 'topojson-simplify';
import { geoPath } from 'd3-geo';

const FIPS = {
  '01': ['AL', 'Alabama'], '02': ['AK', 'Alaska'], '04': ['AZ', 'Arizona'], '05': ['AR', 'Arkansas'],
  '06': ['CA', 'California'], '08': ['CO', 'Colorado'], '09': ['CT', 'Connecticut'], '10': ['DE', 'Delaware'],
  '11': ['DC', 'District of Columbia'], '12': ['FL', 'Florida'], '13': ['GA', 'Georgia'], '15': ['HI', 'Hawaii'],
  '16': ['ID', 'Idaho'], '17': ['IL', 'Illinois'], '18': ['IN', 'Indiana'], '19': ['IA', 'Iowa'],
  '20': ['KS', 'Kansas'], '21': ['KY', 'Kentucky'], '22': ['LA', 'Louisiana'], '23': ['ME', 'Maine'],
  '24': ['MD', 'Maryland'], '25': ['MA', 'Massachusetts'], '26': ['MI', 'Michigan'], '27': ['MN', 'Minnesota'],
  '28': ['MS', 'Mississippi'], '29': ['MO', 'Missouri'], '30': ['MT', 'Montana'], '31': ['NE', 'Nebraska'],
  '32': ['NV', 'Nevada'], '33': ['NH', 'New Hampshire'], '34': ['NJ', 'New Jersey'], '35': ['NM', 'New Mexico'],
  '36': ['NY', 'New York'], '37': ['NC', 'North Carolina'], '38': ['ND', 'North Dakota'], '39': ['OH', 'Ohio'],
  '40': ['OK', 'Oklahoma'], '41': ['OR', 'Oregon'], '42': ['PA', 'Pennsylvania'], '44': ['RI', 'Rhode Island'],
  '45': ['SC', 'South Carolina'], '46': ['SD', 'South Dakota'], '47': ['TN', 'Tennessee'], '48': ['TX', 'Texas'],
  '49': ['UT', 'Utah'], '50': ['VT', 'Vermont'], '51': ['VA', 'Virginia'], '53': ['WA', 'Washington'],
  '54': ['WV', 'West Virginia'], '55': ['WI', 'Wisconsin'], '56': ['WY', 'Wyoming'],
};

const topology = JSON.parse(readFileSync('node_modules/us-atlas/states-albers-10m.json', 'utf8'));
const simple = simplify(presimplify(topology), quantile(presimplify(topology), 0.12));
const path = geoPath().digits(1);
const { features } = feature(simple, simple.objects.states);

const states = [];
for (const f of features) {
  const entry = FIPS[String(f.id).padStart(2, '0')];
  if (!entry) continue;
  const polygons = f.geometry.type === 'MultiPolygon'
    ? f.geometry.coordinates.map((coordinates) => ({ type: 'Polygon', coordinates }))
    : [f.geometry];
  const largest = polygons.reduce((best, p) => (path.area(p) > path.area(best) ? p : best));
  const [cx, cy] = path.centroid(largest);
  states.push({ code: entry[0], name: entry[1], d: path(f), cx: Math.round(cx), cy: Math.round(cy) });
}
states.sort((a, b) => a.code.localeCompare(b.code));

const out =
  '/* Generated by scripts/build-us-map.mjs from us-atlas (U.S. Census boundaries). Do not edit. */\n\n' +
  'export interface UsState {\n  readonly code: string;\n  readonly name: string;\n  readonly d: string;\n  readonly cx: number;\n  readonly cy: number;\n}\n\n' +
  'export const US_MAP_SIZE = { width: 975, height: 610 } as const;\n\n' +
  'export const US_STATES: readonly UsState[] = ' + JSON.stringify(states) + ';\n';
writeFileSync('src/ui/usPaths.ts', out);
console.log(states.length + ' states, ' + Math.round(out.length / 1024) + ' KB');
